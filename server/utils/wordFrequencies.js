export { STOP_WORDS };

/**
 * Tokenize a single message body. Lowercase, strip non-letter chars, split on
 * whitespace, drop short tokens and stop words.
 */
export function tokenize(content) {
  return (content || "")
    .toLowerCase()
    .replace(/[^a-z\s'-]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOP_WORDS.has(w));
}

/**
 * Compute word frequencies on-the-fly across a list of messages.
 * Returns words appearing at least twice, sorted by count descending,
 * capped at 40 entries. Used for live (non-stored) round views.
 */
export function computeLiveWordFrequencies(messages) {
  const wordCounts = {};
  for (const msg of messages) {
    for (const word of tokenize(msg.content)) {
      wordCounts[word] = (wordCounts[word] || 0) + 1;
    }
  }

  return Object.entries(wordCounts)
    .filter(([, count]) => count > 1)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 40)
    .map(([word, count]) => ({ word, count }));
}
